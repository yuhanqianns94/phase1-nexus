def top_article_rows(scored: list[dict[str, Any]], top_k: int) -> list[dict[str, Any]]:
    return [
        {
            "pmcid": item["pmcid"],
            "similarity": round(item["similarity"], 6),
            "curve_similarity_weight": round(item["similarity"], 6),
            "available_weight": round(item["available_weight"], 6),
            "field_scores": {
                key: round(value, 6)
                for key, value in sorted(item["field_scores"].items())
            },
        }
        for item in scored[: max(0, top_k)]
    ]


