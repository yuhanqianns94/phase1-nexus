def similarity_score_statistics(
    scored: list[dict[str, Any]],
    *,
    bin_width: float = 0.05,
) -> dict[str, Any]:
    """Summarize raw similarity S over every scored historical article."""

    values = sorted(max(0.0, float(article["similarity"])) for article in scored)
    if not values:
        return {
            "article_count": 0,
            "min": None,
            "max": None,
            "mean": None,
            "median": None,
            "stdev": None,
            "p10": None,
            "p25": None,
            "p75": None,
            "p90": None,
            "histogram": [],
        }

    count = len(values)
    mean = sum(values) / count
    if count == 1:
        variance = 0.0
    else:
        variance = sum((value - mean) ** 2 for value in values) / (count - 1)

    def percentile(fraction: float) -> float:
        if count == 1:
            return values[0]
        position = (count - 1) * fraction
        lower = int(math.floor(position))
        upper = int(math.ceil(position))
        if lower == upper:
            return values[lower]
        weight = position - lower
        return values[lower] * (1.0 - weight) + values[upper] * weight

    histogram: list[dict[str, Any]] = []
    edge = 0.0
    while edge < 1.0 - 1e-12:
        next_edge = min(1.0, round(edge + bin_width, 10))
        bin_count = sum(
            1
            for value in values
            if edge <= value < next_edge or (next_edge >= 1.0 - 1e-12 and value == 1.0)
        )
        if bin_count:
            histogram.append(
                {
                    "bin_low": round(edge, 6),
                    "bin_high": round(next_edge, 6),
                    "count": bin_count,
                    "fraction": round(bin_count / count, 6),
                }
            )
        edge = next_edge

    return {
        "article_count": count,
        "min": round(values[0], 6),
        "max": round(values[-1], 6),
        "mean": round(mean, 6),
        "median": round(percentile(0.5), 6),
        "stdev": round(math.sqrt(variance), 6),
        "p10": round(percentile(0.10), 6),
        "p25": round(percentile(0.25), 6),
        "p75": round(percentile(0.75), 6),
        "p90": round(percentile(0.90), 6),
        "histogram": histogram,
    }


def print_similarity_score_statistics(diagnostics: dict[str, Any]) -> None:
    """Print library-wide raw similarity S summary for the terminal."""

    stats = diagnostics.get("similarity_score_statistics")
    if not isinstance(stats, dict) or not stats.get("article_count"):
        print("Similarity score statistics: no scored articles")
        return
    print(
        "Similarity score statistics (all scored articles, raw S): "
        f"n={stats['article_count']}, "
        f"min={stats['min']:.4f}, "
        f"p10={stats['p10']:.4f}, "
        f"p25={stats['p25']:.4f}, "
        f"median={stats['median']:.4f}, "
        f"mean={stats['mean']:.4f}, "
        f"p75={stats['p75']:.4f}, "
        f"p90={stats['p90']:.4f}, "
        f"max={stats['max']:.4f}, "
        f"stdev={stats['stdev']:.4f}"
    )
    histogram = stats.get("histogram") or []
    if histogram:
        rendered = [
            f"[{row['bin_low']:.2f},{row['bin_high']:.2f}): {row['count']}"
            for row in histogram
        ]
        print("  S histogram: " + "; ".join(rendered))


def print_all_scored_similarities(
    articles: list[dict[str, Any]],
    *,
    label: str = "All scored articles (by raw similarity S)",
) -> None:
    """Print every article PMCID and raw similarity S to the terminal."""

    if not articles:
        print(f"{label}: none")
        return
    print(f"{label}:")
    width = max(2, len(str(len(articles))))
    for rank, article in enumerate(articles, start=1):
        print(
            f"  {rank:{width}d}. {article['pmcid']}  "
            f"S={float(article['similarity']):.6f}"
        )


def plot_comparison(result: dict[str, Any], plot_path: Path) -> None:
    """Draw curves, extracted observations, MAD caps, and extrapolation status."""

    os.environ.setdefault("MPLCONFIGDIR", str(plot_path.parent / ".matplotlib"))
    Path(os.environ["MPLCONFIGDIR"]).mkdir(parents=True, exist_ok=True)
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    query = result["query"]
    leave_one_out = result.get("leave_one_out_validation")
    figure, axis = plt.subplots(figsize=(11.5, 5.5))
    methods = result["toxicity_curve"]
    styles = {
        "article_line_weighted": (
            "tab:orange",
            "Similarity-weighted Bayesian historical-curve mixture",
        ),
        "article_posterior_draw_pool": (
            "tab:green",
            "Similarity-weighted article-component posterior mixture",
        ),
    }

    historical_evidence = [
        point
        for line in methods.get("article_line_weighted", {}).get("historical_lines", [])
        for point in line.get("source_points", [])
    ]
    extracted_historical_evidence = [
        point
        for point in historical_evidence
        if point.get("dlt_value_origins", ["extracted"]) == ["extracted"]
    ]
    inferred_historical_evidence = [
        point
        for point in historical_evidence
        if point not in extracted_historical_evidence
    ]
    if extracted_historical_evidence:
        axis.scatter(
            [point["canonical_dose"] for point in extracted_historical_evidence],
            [
                point["observed_dlt_probability"]
                for point in extracted_historical_evidence
            ],
            s=[
                min(100, 18 + 5 * point.get("n_patients", 1))
                for point in extracted_historical_evidence
            ],
            facecolors="none",
            edgecolors="black",
            linewidths=0.8,
            alpha=0.55,
            label=(
                "Historical extracted DLT rate"
                if leave_one_out
                else "Actual extracted DLT rate"
            ),
            zorder=3,
        )
    if inferred_historical_evidence:
        axis.scatter(
            [point["canonical_dose"] for point in inferred_historical_evidence],
            [
                point["observed_dlt_probability"]
                for point in inferred_historical_evidence
            ],
            s=34,
            marker="v",
            facecolors="none",
            edgecolors="dimgray",
            linewidths=0.9,
            alpha=0.75,
            label="Model-inferred unreported dose-level zero",
            zorder=3,
        )

    for name, (color, label) in styles.items():
        method = methods.get(name)
        if not method or method.get("status") != "fitted":
            continue
        rows = [
            row
            for row in method["curve_points"]
            if row.get("dlt_probability") is not None
        ]
        if not rows:
            continue
        doses = [row["dose"] for row in rows]
        probabilities = [row["dlt_probability"] for row in rows]
        axis.plot([], [], color=color, marker="o", label=label)
        axis.scatter(doses, probabilities, color=color, s=24, zorder=4)
        for index in range(len(rows) - 1):
            left, right = rows[index], rows[index + 1]
            extrapolated = (
                left.get("extrapolation_weight_fraction", 0) > 0
                or right.get("extrapolation_weight_fraction", 0) > 0
            )
            axis.plot(
                [left["dose"], right["dose"]],
                [left["dlt_probability"], right["dlt_probability"]],
                color=color,
                linewidth=2,
                linestyle="--" if extrapolated else "-",
                zorder=2,
            )

        intervals = [row.get("posterior_credible_interval_95") for row in rows]
        if all(interval and interval["low"] is not None for interval in intervals):
            axis.fill_between(
                doses,
                [interval["low"] for interval in intervals],
                [interval["high"] for interval in intervals],
                color=color,
                alpha=0.12,
                label=(
                    "Bayesian posterior 95% credible interval"
                    if name == "article_line_weighted"
                    else (
                        "95% similarity-weighted mixture interval"
                        if name == "article_posterior_draw_pool"
                        else None
                    )
                ),
            )

    article_lines = methods.get("article_line_weighted", {}).get("historical_lines", [])
    mad_values = {
        line["mad_cap"] for line in article_lines if line.get("mad_cap") is not None
    }
    for index, mad in enumerate(sorted(mad_values)):
        axis.axvline(
            mad,
            color="gray",
            linestyle=":",
            linewidth=1.2,
            alpha=0.75,
            label=("All-zero not-reached Bayesian arm MAD cap" if index == 0 else None),
            zorder=0,
        )

    if leave_one_out:
        standard_answer = leave_one_out["standard_answer"]
        answer_points = standard_answer["points"]
        posthoc_reference = leave_one_out.get("posthoc_bayesian_reference_curve")
        if (
            isinstance(posthoc_reference, dict)
            and posthoc_reference.get("status") == "fitted"
        ):
            reference_rows = [
                row
                for row in posthoc_reference.get("curve_points", [])
                if row.get("dlt_probability") is not None
            ]
            if reference_rows:
                reference_doses = [row["dose"] for row in reference_rows]
                reference_probabilities = [
                    row["dlt_probability"] for row in reference_rows
                ]
                axis.plot(
                    reference_doses,
                    reference_probabilities,
                    color="tab:blue",
                    linewidth=2,
                    label=("Post-hoc Bayesian fit to held-out DLT " "(reference only)"),
                    zorder=5,
                )
                reference_intervals = [
                    row.get("posterior_credible_interval_95") for row in reference_rows
                ]
                if all(
                    interval and interval.get("low") is not None
                    for interval in reference_intervals
                ):
                    axis.fill_between(
                        reference_doses,
                        [interval["low"] for interval in reference_intervals],
                        [interval["high"] for interval in reference_intervals],
                        color="tab:blue",
                        alpha=0.08,
                        label="Post-hoc reference 95% credible interval",
                        zorder=4,
                    )
        historical_logistic = leave_one_out.get(
            "historical_similarity_weighted_mle_logistic_reference_curve"
        )
        if (
            isinstance(historical_logistic, dict)
            and historical_logistic.get("status") == "fitted"
        ):
            logistic_rows = [
                row
                for row in historical_logistic.get("curve_points", [])
                if row.get("dlt_probability") is not None
            ]
            if logistic_rows:
                axis.plot(
                    [row["dose"] for row in logistic_rows],
                    [row["dlt_probability"] for row in logistic_rows],
                    color="tab:purple",
                    linewidth=2,
                    linestyle="--",
                    label=(
                        "Similarity-weighted historical MLE logistic "
                        "(reference only; not held-out fit)"
                    ),
                    zorder=5,
                )
        extracted_answer_points = [
            point
            for point in answer_points
            if point.get("dlt_value_origins", ["extracted"]) == ["extracted"]
        ]
        inferred_answer_points = [
            point for point in answer_points if point not in extracted_answer_points
        ]
        axis.scatter(
            [point["dose"] for point in extracted_answer_points],
            [point["observed_dlt_probability"] for point in extracted_answer_points],
            marker="X",
            s=72,
            color="crimson",
            edgecolors="white",
            linewidths=0.6,
            label=f"Held-out {leave_one_out['heldout_pmcid']} observed DLT",
            zorder=6,
        )
        if inferred_answer_points:
            axis.scatter(
                [point["dose"] for point in inferred_answer_points],
                [point["observed_dlt_probability"] for point in inferred_answer_points],
                marker="v",
                s=62,
                facecolors="none",
                edgecolors="crimson",
                linewidths=1.2,
                label=(f"Held-out {leave_one_out['heldout_pmcid']} inferred zero DLT"),
                zorder=6,
            )
        heldout_mtd = leave_one_out.get("heldout_mtd")
        if (
            isinstance(heldout_mtd, dict)
            and isinstance(heldout_mtd.get("dose"), (int, float))
            and math.isfinite(float(heldout_mtd["dose"]))
            and float(heldout_mtd["dose"]) > 0
        ):
            mtd_dose = float(heldout_mtd["dose"])
            axis.axvline(
                mtd_dose,
                color="crimson",
                linestyle="--",
                linewidth=1.8,
                alpha=0.9,
                label=(
                    f"Held-out MTD ({mtd_dose:g} "
                    f"{heldout_mtd.get('unit') or query['target_unit']})"
                ),
                zorder=5,
            )
            axis.annotate(
                "MTD",
                xy=(mtd_dose, 0.97),
                xytext=(4, 0),
                textcoords="offset points",
                color="crimson",
                fontsize=8,
                ha="left",
                va="top",
            )

    axis.set_ylim(-0.03, 1.03)
    curve_doses = list(query["planned_doses"])
    heldout_mtd = leave_one_out.get("heldout_mtd") if leave_one_out else None
    if (
        isinstance(heldout_mtd, dict)
        and isinstance(heldout_mtd.get("dose"), (int, float))
        and math.isfinite(float(heldout_mtd["dose"]))
        and float(heldout_mtd["dose"]) > 0
    ):
        curve_doses.append(float(heldout_mtd["dose"]))
    if len(curve_doses) >= 2:
        axis.set_xlim(min(curve_doses), max(curve_doses))
    elif len(curve_doses) == 1:
        axis.set_xlim(curve_doses[0] * 0.9, curve_doses[0] * 1.1)
    axis.set_xlabel(f"Curve dose ({query['target_unit']})")
    axis.set_ylabel("Predicted DLT probability")
    prior_name = (result.get("bayesian_curve_parameters") or {}).get("prior_name")
    base_title = (
        (
            f"Leave-one-out toxicity curve: {query['toxicity_curve_drug']} "
            f"({leave_one_out['heldout_pmcid']} held out)"
        )
        if leave_one_out
        else f"Similarity-weighted toxicity curve: {query['toxicity_curve_drug']}"
    )
    axis.set_title(base_title)
    axis.grid(alpha=0.25)
    if axis.get_legend_handles_labels()[0]:
        axis.legend(loc="best", fontsize=8)
    annotate_figure_with_prior_panel(figure, prior_name)
    plot_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(plot_path, dpi=180)
    plt.close(figure)


def estimate_toxicity_curve(
    query: dict[str, Any],
    records: list[dict[str, Any]],
    *,
    embedding_backend: str,
    embedding_model: str,
    embedding_cache: Path,
    top_k: int,
    ignored_query_fields: list[str] | None = None,
    auto_grid_points: int = 101,
    evaluation_doses: list[float] | tuple[float, ...] = (),
    field_weights: dict[str, float] | None = None,
    similarity_threshold: float = 0.0,
    similarity_parameter_source: str = "built_in_defaults",
    bayesian_cache: dict[str, Any],
    bayesian_prior: str,
    bayesian_cache_metadata: dict[str, Any] | None = None,
    single_observation_reliability_weight: float = (
        DEFAULT_SINGLE_OBSERVATION_RELIABILITY_WEIGHT
    ),
    power_likelihood_enabled: bool = False,
    power_likelihood_random_effects_enabled: bool = False,
    power_likelihood_random_intercept_slope_enabled: bool = True,
    power_likelihood_borrowing_strength: float = DEFAULT_BORROWING_STRENGTH,
    power_likelihood_ess_cap: float = DEFAULT_HISTORICAL_ESS_CAP,
    random_intercept_scale_prior_mean: float = DEFAULT_INTERCEPT_SCALE_LATENT_MEAN,
    random_intercept_scale_prior_sd: float = DEFAULT_INTERCEPT_SCALE_LATENT_SD,
    random_slope_scale_prior_mean: float = DEFAULT_SLOPE_SCALE_LATENT_MEAN,
    random_slope_scale_prior_sd: float = DEFAULT_SLOPE_SCALE_LATENT_SD,
    historical_article_selection_mode: str = AUTOMATIC_SELECTION_MODE,
    historical_article_candidate_basis: str = THRESHOLD_CANDIDATE_BASIS,
    historical_article_top_n: int = DEFAULT_HISTORICAL_ARTICLE_TOP_N,
    historical_article_ids: list[str] | tuple[str, ...] | None = None,
    historical_article_candidate_snapshot_sha256: str | None = None,
) -> dict[str, Any]:
    spec = parse_toxicity_query(query)
    resolved_field_weights = normalize_field_weights(field_weights)
    if any("_comparison_profile" in r["data"] for r in records):
        from ..profile_similarity import normalize_weights as profile_weights
        resolved_field_weights = profile_weights(resolved_field_weights)
    resolved_threshold = validate_similarity_threshold(similarity_threshold)
    scored_before_threshold, backend_used = score_library(
        query,
        records,
        embedding_backend=embedding_backend,
        embedding_model=embedding_model,
        embedding_cache=embedding_cache,
        field_weights=resolved_field_weights,
    )
    scored_after_threshold_count = sum(
        1
        for article in scored_before_threshold
        if float(article.get("similarity", 0.0)) >= resolved_threshold
    )
    scored, historical_article_selection = apply_historical_article_selection(
        scored_before_threshold,
        similarity_threshold=resolved_threshold,
        selection_mode=historical_article_selection_mode,
        candidate_basis=historical_article_candidate_basis,
        top_n=historical_article_top_n,
        selected_document_ids=historical_article_ids,
        candidate_snapshot_sha256=historical_article_candidate_snapshot_sha256,
    )
    if spec.planned_doses:
        dose_grid = {
            "mode": "explicit_query_planned_doses",
            "generated_grid_point_count": len(spec.planned_doses),
            "additional_evaluation_dose_count": 0,
        }
    else:
        auto_doses, dose_grid = derive_auto_curve_doses(
            scored,
            spec,
            additional_doses=evaluation_doses,
            grid_points=auto_grid_points,
        )
        if not auto_doses:
            if scored_before_threshold and not scored:
                raise ValueError(
                    "No historical articles meet the configured similarity_threshold "
                    f"(S >= {resolved_threshold:g})."
                )
            raise ValueError(
                "No comparable historical DLT doses were found for the requested "
                "canonical Dose_Unit."
            )
        spec = replace(spec, planned_doses=auto_doses)
    original_method = estimate_article_line_weighted(
        scored,
        spec,
        bayesian_cache=bayesian_cache,
        bayesian_prior=bayesian_prior,
        single_observation_reliability_weight=single_observation_reliability_weight,
    )
    posterior_draw_pool_method = estimate_article_posterior_draw_pool(
        original_method.get("historical_lines", []),
        spec,
        bayesian_prior=bayesian_prior,
    )
    methods = {
        "article_line_weighted": original_method,
        "article_posterior_draw_pool": posterior_draw_pool_method,
    }
    if power_likelihood_random_intercept_slope_enabled:
        methods["power_likelihood_random_intercept_slope"] = (
            estimate_power_likelihood_random_intercept_slope_curve(
                original_method.get("historical_lines", []),
                spec,
                bayesian_prior=bayesian_prior,
                settings=RandomInterceptSlopeSettings(
                    historical_ess_cap=power_likelihood_ess_cap,
                    borrowing_strength=power_likelihood_borrowing_strength,
                    intercept_scale_latent_mean=random_intercept_scale_prior_mean,
                    intercept_scale_latent_sd=random_intercept_scale_prior_sd,
                    slope_scale_latent_mean=random_slope_scale_prior_mean,
                    slope_scale_latent_sd=random_slope_scale_prior_sd,
                ),
            )
        )
    if power_likelihood_enabled:
        methods["power_likelihood"] = estimate_power_likelihood_curve(
            original_method.get("historical_lines", []),
            spec,
            bayesian_prior=bayesian_prior,
            settings=PowerLikelihoodSettings(
                historical_ess_cap=power_likelihood_ess_cap,
                borrowing_strength=power_likelihood_borrowing_strength,
            ),
        )
    if power_likelihood_random_effects_enabled:
        methods["power_likelihood_random_effects"] = (
            estimate_power_likelihood_random_effects_curve(
                original_method.get("historical_lines", []),
                spec,
                bayesian_prior=bayesian_prior,
                settings=RandomEffectsSettings(
                    historical_ess_cap=power_likelihood_ess_cap,
                    borrowing_strength=power_likelihood_borrowing_strength,
                ),
            )
        )

    raw_similarities = [max(0.0, article["similarity"]) for article in scored]
    similarity_sum = sum(raw_similarities)
    diagnostic_relative_similarities = (
        [similarity / similarity_sum for similarity in raw_similarities]
        if similarity_sum > 0
        else []
    )
    prediction_run_identity_sha256 = _canonical_hash(
        {
            "model_version": PREDICTION_MODEL_VERSION,
            "query": {
                "drug": spec.curve_drug,
                "unit": spec.target_unit,
                "trial_type": spec.trial_type,
                "doses": list(spec.planned_doses),
            },
            "bayesian_prior": bayesian_prior,
            "power_likelihood": {
                "borrowing_strength": power_likelihood_borrowing_strength,
                "ess_cap": power_likelihood_ess_cap,
                "intercept_scale_prior": [
                    random_intercept_scale_prior_mean,
                    random_intercept_scale_prior_sd,
                ],
                "slope_scale_prior": [
                    random_slope_scale_prior_mean,
                    random_slope_scale_prior_sd,
                ],
            },
            "historical_article_selection": historical_article_selection,
            "source_library_fingerprint": bayesian_cache.get(
                "source_library_fingerprint_sha256"
            ),
        }
    )
    return {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "prediction_model_version": PREDICTION_MODEL_VERSION,
        "prediction_run_identity_sha256": prediction_run_identity_sha256,
        "probability_target": (
            "P(DLT at curve doses | pre-trial query, full similar historical "
            "compact extraction library)"
        ),
        "ignored_query_fields": ignored_query_fields or [],
        "query": {
            "toxicity_curve_drug": spec.curve_drug,
            "target_unit": spec.target_unit,
            "trial_type": spec.trial_type,
            "planned_doses": list(spec.planned_doses),
            "dose_grid": dose_grid,
            "similarity_threshold": resolved_threshold,
        },
        "article_count": len(records),
        "similarity_parameters": {
            "field_weights": resolved_field_weights,
            "similarity_threshold": resolved_threshold,
            "source": similarity_parameter_source,
        },
        "historical_article_selection": historical_article_selection,
        "bayesian_curve_parameters": {
            "prior_name": bayesian_prior,
            "single_observation_reliability_weight": (
                single_observation_reliability_weight
            ),
            "power_likelihood": {
                "model_version": THREE_METHOD_MODEL_VERSION,
                "random_intercept_slope_enabled": (
                    power_likelihood_random_intercept_slope_enabled
                ),
                "enabled": power_likelihood_enabled,
                "random_effects_enabled": power_likelihood_random_effects_enabled,
                "borrowing_strength": power_likelihood_borrowing_strength,
                "historical_ess_cap": power_likelihood_ess_cap,
                "random_intercept_scale_prior": {
                    "latent_mean": random_intercept_scale_prior_mean,
                    "latent_sd": random_intercept_scale_prior_sd,
                },
                "random_slope_scale_prior": {
                    "latent_mean": random_slope_scale_prior_mean,
                    "latent_sd": random_slope_scale_prior_sd,
                },
                "current_curve_preserved_as_article_line_weighted": True,
            },
            "cache": bayesian_cache_metadata
            or {
                "format": bayesian_cache.get("format"),
                "model": bayesian_cache.get("model"),
                "source_library_fingerprint_sha256": bayesian_cache.get(
                    "source_library_fingerprint_sha256"
                ),
                "prior_catalog_fingerprint_sha256": bayesian_cache.get(
                    "prior_catalog_fingerprint_sha256"
                ),
            },
        },
        "curve_similarity_weight_basis": (
            "raw_field_weighted_similarity_without_full_library_normalization"
        ),
        "embedding_backend_requested": embedding_backend,
        "embedding_backend_used": backend_used,
        "embedding_model": embedding_model if backend_used == "openai" else None,
        "similarity_diagnostics": {
            "articles_scored": len(scored_before_threshold),
            "articles_included_after_threshold": scored_after_threshold_count,
            "articles_excluded_below_threshold": (
                len(scored_before_threshold) - scored_after_threshold_count
            ),
            "retained_for_curve_after_article_selection": len(scored),
            "max_similarity_before_threshold": (
                round(scored_before_threshold[0]["similarity"], 6)
                if scored_before_threshold
                else 0.0
            ),
            "max_similarity": round(scored[0]["similarity"], 6) if scored else 0.0,
            "raw_similarity_sum": round(similarity_sum, 6),
            "relative_similarity_ess_for_diagnostics": round(
                effective_sample_size(diagnostic_relative_similarities), 3
            ),
            "similarity_score_statistics": similarity_score_statistics(
                scored_before_threshold
            ),
        },
        "all_scored_articles": all_scored_similarity_rows(scored_before_threshold),
        "top_similar_articles": top_article_rows(scored, top_k),
        "toxicity_curve": methods,
    }


def print_curve_summary(result: dict[str, Any]) -> None:
    """Print the fitted equation and the most useful support diagnostics."""

    query = result["query"]
    print(
        f"Target: {query['toxicity_curve_drug']} | "
        f"unit={query['target_unit']} | "
        f"trial_type={query['trial_type']} | "
        f"dose grid={query['dose_grid']['mode']} "
        f"({len(query['planned_doses'])} points)"
    )
    diagnostics = result.get("similarity_diagnostics", {})
    print(
        "Similarity filter: "
        f"S ≥ {query['similarity_threshold']:.3f} | "
        f"{diagnostics.get('articles_included_after_threshold', 0)}/"
        f"{diagnostics.get('articles_scored', 0)} articles retained"
    )
    bayesian = result.get("bayesian_curve_parameters", {})
    if bayesian.get("prior_name"):
        print(
            "Bayesian historical curves: "
            f"prior={bayesian['prior_name']} | "
            "posterior=Laplace Binomial-logistic cache"
        )
    print_similarity_score_statistics(diagnostics)
    print_all_scored_similarities(result.get("all_scored_articles", []))
    method_result = result["toxicity_curve"]["article_line_weighted"]
    print(f"Similarity-weighted curve: {method_result['status']}")
    if method_result["status"] == "fitted":
        print(
            "  Equation: pointwise similarity-weighted Bayesian historical-curve "
            "mixture (no single global equation)."
        )
    stats = method_result.get("aggregation_stats", {})
    support = ", ".join(
        f"{label}={value}"
        for label, value in (
            ("articles", stats.get("article_count")),
            ("historical segments", stats.get("line_count")),
            ("segment-weight ESS", stats.get("segment_weight_ess")),
        )
        if value is not None
    )
    if support:
        print(f"  Historical support: {support}")


def main() -> int:
    args = parse_args()
    raw_query = json.loads(args.query_json.read_text(encoding="utf-8"))
    query, ignored_fields = pretrial_query_only(raw_query)
    records = load_extractions(args.extraction_dir, args.pattern)
    if not records:
        raise SystemExit(f"No extraction records found in {args.extraction_dir}")
    try:
        bayesian_cache = load_bayesian_curve_cache(
            args.bayesian_cache,
            records=records,
            prior_name=args.bayesian_prior,
            prior_catalog_path=args.bayesian_prior_catalog,
        )
        bayesian_cache_metadata = cache_metadata_for_result(
            bayesian_cache, args.bayesian_prior, args.bayesian_cache
        )
        field_weights, similarity_threshold, parameter_source = (
            resolve_similarity_parameters(
                path=args.similarity_params,
                use_manual_default=not args.no_manual_similarity_params,
                threshold_override=args.similarity_threshold,
            )
        )
        result = estimate_toxicity_curve(
            query,
            records,
            embedding_backend=args.embedding_backend,
            embedding_model=args.embedding_model,
            embedding_cache=args.embedding_cache,
            top_k=args.top_k,
            ignored_query_fields=ignored_fields,
            auto_grid_points=args.auto_grid_points,
            field_weights=field_weights,
            similarity_threshold=similarity_threshold,
            similarity_parameter_source=parameter_source,
            bayesian_cache=bayesian_cache,
            bayesian_prior=args.bayesian_prior,
            bayesian_cache_metadata=bayesian_cache_metadata,
            single_observation_reliability_weight=(args.single_observation_reliability),
        )
    except ValueError as error:
        raise SystemExit(str(error)) from error
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    if not args.no_plot:
        plot_comparison(result, args.plot)
    print(f"Wrote {args.output}")
    if not args.no_plot:
        print(f"Wrote {args.plot}")
    print_curve_summary(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
